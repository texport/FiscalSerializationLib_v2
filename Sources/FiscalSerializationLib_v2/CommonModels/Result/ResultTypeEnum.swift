/// Внутреннее перечисление `ResultTypeEnum`, используемое для обработки кодов ответов, получаемых от сервера оператора фискальных данных (ОФД).
///
/// Это перечисление описывает возможные результаты выполнения команд и служит для интерпретации статуса ответа от ОФД.
/// Каждое значение содержит описание причины ошибки или успешного выполнения команды.
///
/// ### Примечание:
/// Данное перечисление используется исключительно для внутренней логики библиотеки и недоступно для внешних пользователей.
enum ResultTypeEnum: UInt32 {

    /// Команда выполнена успешно.
    ///
    /// Аппарат работает в штатном режиме, операция завершена без ошибок.
    case ok = 0

    /// Неизвестный идентификатор устройства.
    ///
    /// Сервер не распознал ID устройства. Это означает, что аппарат не зарегистрирован в системе и должен автоматически заблокироваться.
    /// Решение: зарегистрируйте устройство в системе и повторите попытку.
    case unknownId = 1

    /// Неверный токен.
    ///
    /// Токен доступа недействителен или истек. Требуется сброс токена, иначе устройство будет заблокировано до ввода корректного токена.
    /// Решение: выполните процедуру повторной авторизации и получите новый токен.
    case invalidToken = 2

    /// Ошибка протокола.
    ///
    /// Возникает, если запрос был сформирован неверно или не соответствует требованиям протокола. Устройство должно приостановить операции до устранения проблемы.
    /// Решение: обратитесь в сервисную службу для диагностики и исправления.
    case protocolError = 3

    /// Неизвестная команда.
    ///
    /// Сервер не распознал тип команды. Это может быть вызвано неверным форматом команды или её отсутствием в текущей версии протокола.
    /// Решение: проверьте правильность отправляемой команды.
    case unknownCommand = 4

    /// Команда не поддерживается сервером.
    ///
    /// Сервер ОФД не поддерживает выполнение этой команды. Возможно, команда устарела или недоступна в текущей версии системы.
    /// Решение: обновите ПО кассового аппарата или обратитесь к разработчику.
    case unsupportedCommand = 5

    /// Неверные настройки устройства.
    ///
    /// Ошибка конфигурации кассы. (В текущей версии не используется, зарезервировано для будущих обновлений).
    case invalidConfiguration = 6

    /// Использование SSL запрещено.
    ///
    /// Сервер ОФД отклонил соединение, так как использование SSL в текущей конфигурации запрещено. Устройство должно перейти в аварийный режим.
    /// Решение: измените настройки конфигурации и повторите попытку.
    case sslNotAllowed = 7

    /// Неправильный номер запроса.
    ///
    /// Порядковый номер `REQNUM` совпадает с предыдущим запросом, но токен другой. Это может быть попытка повторного использования номера запроса.
    /// Решение: убедитесь в уникальности номера запроса.
    case invalidRequestNumber = 8

    /// Неправильная попытка повторного запроса.
    ///
    /// Параметры `REQNUM` и `TOKEN` совпадают с предыдущим запросом, но команда отличается. Это указывает на нарушение последовательности запросов.
    case invalidRetryRequest = 9

    /// Невозможно отменить чек.
    ///
    /// Отмена возможна только для последнего фискализированного чека, если после него не было других команд, кроме служебных.
    /// Решение: отмена чека невозможна, если с момента его регистрации были другие операции.
    case cantCancelTicket = 10

    /// Время открытой смены истекло.
    ///
    /// Смена открыта слишком долго и требует принудительного закрытия командой `COMMAND_CLOSE_SHIFT`.
    case openShiftTimeoutExpired = 11

    /// Неправильное имя пользователя или пароль.
    ///
    /// Ошибка аутентификации оператора. (Код устарел и используется для обратной совместимости).
    case invalidLoginPassword = 12

    /// Неверные входные данные.
    ///
    /// Данные, отправленные в запросе, корректны по формату протокола, но содержат логические ошибки в конкретном контексте.
    /// Решение: проверьте корректность передаваемых данных.
    case incorrectRequestData = 13

    /// Недостаточно наличных в кассе.
    ///
    /// Попытка провести расходную операцию при недостатке наличных средств в кассовом аппарате.
    case notEnoughCash = 14

    /// Касса заблокирована.
    ///
    /// Устройство заблокировано сервером либо снято с учета. Возможно, не переданы обязательные параметры в команде `COMMAND_TICKET`.
    /// Решение: обратитесь в службу поддержки ОФД для выяснения причин блокировки.
    case blocked = 15

    /// Совпадение ИИН/БИН покупателя и продавца.
    ///
    /// Указан один и тот же ИИН/БИН для покупателя и продавца, что недопустимо по требованиям законодательства.
    /// Решение: исправьте данные и отправьте чек повторно.
    case sameTaxpayerAndCustomer = 17

    /// Сервис временно недоступен.
    ///
    /// Сервер ОФД временно недоступен из-за технических проблем. Устройство должно разорвать соединение и повторить попытку позже.
    case serviceTemporarilyUnavailable = 254

    /// Неизвестная ошибка.
    ///
    /// Произошла ошибка, которую невозможно идентифицировать. Устройство должно разорвать соединение и попытаться снова через некоторое время.
    case unknownError = 255

    /// Описание кода ответа.
    ///
    /// Возвращает текстовое описание причины ошибки или успешного выполнения команды.
    var description: String {
        switch self {
        case .ok: return "Команда выполнена успешно, аппарат работает в штатном режиме."
        case .unknownId: return "Неизвестный ID устройства. Аппарат не зарегистрирован в системе и должен заблокироваться."
        case .invalidToken: return "Неверный токен, требуется сброс токена. Устройство блокируется до ввода корректного токена."
        case .protocolError: return "Ошибка протокола, необходимо обратиться в сервисную службу."
        case .unknownCommand: return "Неизвестная команда, ошибка протокола."
        case .unsupportedCommand: return "Команда не поддерживается сервером."
        case .invalidConfiguration: return "Неверные настройки устройства."
        case .sslNotAllowed: return "Использование SSL запрещено."
        case .invalidRequestNumber: return "Неправильный номер запроса."
        case .invalidRetryRequest: return "Неправильная попытка повторного запроса."
        case .cantCancelTicket: return "Невозможно отменить чек."
        case .openShiftTimeoutExpired: return "Время открытой смены истекло."
        case .invalidLoginPassword: return "Неправильное имя пользователя или пароль."
        case .incorrectRequestData: return "Неверные входные данные."
        case .notEnoughCash: return "Недостаточно наличных в кассе."
        case .blocked: return "Касса заблокирована на сервере."
        case .sameTaxpayerAndCustomer: return "Совпадает ИИН/БИН покупателя и продавца."
        case .serviceTemporarilyUnavailable: return "Сервис временно недоступен."
        case .unknownError: return "Неизвестная ошибка."
        }
    }
}
