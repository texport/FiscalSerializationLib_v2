/// Внутреннее перечисление `CommandTypeEnum` используется для обработки ответов, получаемых от сервера оператора фискальных данных (ОФД).
///
/// Это перечисление описывает различные типы команд, которые могут быть возвращены сервером ОФД в ответ на запросы от контрольно-кассовой машины.
/// Перечисление используется исключительно для внутренней логики библиотеки и недоступно внешним пользователям.
///
/// ### Список доступных команд:
/// - `commandSystem` (0): Системный обмен.
/// - `commandTicket` (1): Фискализация.
/// - `commandCloseShift` (2): Закрытие смены.
/// - `commandReport` (3): Запрос отчетов.
/// - `commandNomenclature` (4): Загрузка номенклатуры.
/// - `commandInfo` (5): Инициализация.
/// - `commandMoneyPlacement` (6): Внесение/снятие денег.
public enum CommandTypeEnum: UInt32 {
    
    /// Системный обмен.
    ///
    /// Используется для отправки служебных пакетов на сервер для проверки доступности канала связи.
    /// Эта команда может использоваться для регулярного обмена пакетами, чтобы поддерживать активное соединение и следить за доступностью сервера.
    case commandSystem = 0
    
    /// Фискализация чека.
    ///
    /// Используется для передачи данных о чеке на сервер ОФД. В ответ на эту команду сервер возвращает номер фискализированного чека.
    /// Данная команда применяется для всех операций, связанных с продажами, возвратами и прочими расчетами.
    case commandTicket = 1
    
    /// Закрытие смены.
    ///
    /// Команда используется для завершения текущей кассовой смены. При успешном выполнении сервер фиксирует окончание смены и сохраняет соответствующие данные.
    /// Это необходимо для учета и отчетности по сменам.
    case commandCloseShift = 2
    
    /// Запрос отчетов (X и Z-отчеты).
    ///
    /// Используется для получения отчетов с сервера ОФД. Запросы могут включать:
    /// - X-отчет — предоставляет данные по продажам за текущую смену.
    /// - Z-отчет — итоговый отчет за закрытую смену.
    case commandReport = 3
    
    /// Запрос номенклатуры.
    ///
    /// Используется для синхронизации номенклатуры товаров между кассовым аппаратом и сервером ОФД. Если сервер имеет более актуальную версию номенклатуры,
    /// она будет передана на кассу для обновления локальной базы данных.
    case commandNomenclature = 4
    
    /// Инициализация кассового аппарата.
    ///
    /// Применяется при запуске кассы для получения текущей конфигурации и регистрационной информации от сервера ОФД. С помощью этой команды устройство
    /// получает актуальные настройки, рекламные тексты и параметры налогообложения.
    case commandInfo = 5
    
    /// Внесение или снятие наличных денежных средств.
    ///
    /// Используется для регистрации операций внесения или изъятия денежных средств из кассы. Команда позволяет учитывать движение наличности в кассовом аппарате.
    case commandMoneyPlacement = 6
    
    /// Описание команды.
    ///
    /// Возвращает текстовое описание каждой команды для лучшего понимания её назначения.
    public var description: String {
        switch self {
        case .commandSystem:
            return """
                   Системный обмен. Отправка серверу служебного пакета для проверки доступности соединения. \
                   Используется для поддержания активного соединения и мониторинга доступности сервера.
                   """
        case .commandTicket:
            return """
                   Фискализация. Передача данных чека на сервер и получение номера чека. \
                   Используется для всех операций, связанных с продажами, возвратами и расчетами.
                   """
        case .commandCloseShift:
            return """
                   Закрытие смены. Фиксация окончания текущей кассовой смены на сервере. \
                   Это необходимо для отчетности и учета сменных операций.
                   """
        case .commandReport:
            return """
                   Запрос отчетов (X и Z). Получение отчетов по продажам за смену. \
                   X-отчет предоставляет данные по текущей смене, Z-отчет — итоговый за закрытую смену.
                   """
        case .commandNomenclature:
            return """
                   Запрос номенклатуры. Синхронизация базы товаров между кассой и сервером ОФД. \
                   Обновление актуальной номенклатуры для корректного учета товаров.
                   """
        case .commandInfo:
            return """
                   Инициализация. Запрос информации о кассе и регистрационных данных при запуске устройства. \
                   Получение настроек, параметров налогообложения и рекламных текстов.
                   """
        case .commandMoneyPlacement:
            return """
                   Внесение/снятие денег. Регистрация операций с наличностью (внесение или изъятие) в кассовом аппарате.
                   """
        }
    }
}
